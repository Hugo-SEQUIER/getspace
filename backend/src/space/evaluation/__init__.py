"""Retrieval-quality measurement for the memory brain.

Parameters: a labelled corpus, a baked embedding cache and one strategy name.
What it does: seeds a disposable pgvector database, drives the real `space.brain` SQL for
every query, and computes the metrics named in docs/RETRIEVAL.md.
Output: a metrics dictionary, a JSON report and a readable table.

The harness retrieves candidates through `brain.search` and `brain.expand`, then
scores the order its selected strategy produces. Strategies may change configuration,
apply a similarity floor, merge candidates or run an optional rerank hook; those
experimental orders need not match the shipped product order.

Modules: `corpus` loads and embeds, `fixture` owns the disposable database, `strategies`
owns the registry, `metrics` owns the arithmetic and `harness` drives the run.
"""

